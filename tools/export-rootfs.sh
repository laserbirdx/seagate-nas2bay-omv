#!/bin/sh
# =============================================================================
#  export-rootfs.sh - build the release assets from a WORKING Seagate NAS 2-Bay
#  running Debian 12 + OMV 7 + both packages from this repository.
#
#  Creates a sanitized copy of the running root filesystem (no passwords, SSH
#  host keys, shares, Samba secrets, logs or machine-id), rebuilds a generic
#  initramfs + uImage for it and packs:
#     seagate-nas2bay-omv7-rootfs-<ver>.img.gz   ext4 image (grown on 1st boot)
#     seagate-nas2bay-omv7-boot-<ver>.tar.gz     uImage + DTB for /dev/md4
#     install-from-stock.sh, SHA256SUMS
#
#  Usage (as root on the NAS):  sh export-rootfs.sh <version> [installer.sh]
#  Output: /media/internal_1/.rootfs-export/out/
#
#  Everything runs with nice/ionice. Do not run other heavy jobs meanwhile -
#  the hardware watchdog resets the NAS if the system stalls.
# =============================================================================
set -e
VER="${1:?usage: export-rootfs.sh <version> [installer.sh]}"
INSTALLER="${2:-}"
WORK="${WORK:-/media/internal_1/.rootfs-export}"
STAGE="$WORK/stage"
OUT="$WORK/out"
KVER="${KVER:-$(uname -r)}"
HOSTNAME_NEW="seagate-nas"
DEF=/usr/share/openmediavault-seagate-nas2bay/defaults

[ "$(id -u)" = 0 ] || { echo "run as root" >&2; exit 1; }
[ -z "$NICED" ] && { NICED=1 exec ionice -c3 nice -n 19 env NICED=1 sh "$0" "$@"; }

say() { echo "==> $*"; }
mkdir -p "$STAGE" "$OUT"
TMPDIR="$WORK/tmp"; export TMPDIR; mkdir -p "$TMPDIR"

# ----------------------------------------------------------------------------- copy
say "Copying root filesystem to $STAGE"
rsync -aHAX --numeric-ids --one-file-system --delete --delete-excluded \
    --exclude='/proc/*' --exclude='/sys/*' --exclude='/dev/*' --exclude='/run/*' \
    --exclude='/tmp/*' --exclude='/mnt/*' --exclude='/media/*' --exclude='/var/tmp/*' \
    --exclude='/lost+found' --exclude='/swapfile' \
    --exclude='/var/cache/apt/archives/*.deb' --exclude='/var/cache/apt/*.bin' \
    --exclude='/var/lib/apt/lists/*' --exclude='/var/log/journal/*' \
    --exclude='/var/lib/openmediavault/rrd/*' --exclude='/var/lib/rrdcached/db/*' \
    --exclude='/var/lib/php/sessions/*' --exclude='/var/cache/openmediavault/*' \
    --exclude='/var/backups/*' --exclude='/root/*' --exclude='/root/.*' \
    --exclude='/home/*/.bash_history' --exclude='/home/*/.ssh' --exclude='/home/*/.cache' \
    / "$STAGE/"

cd "$STAGE"
# ----------------------------------------------------------------------------- sanitize
say "Sanitizing"
rm -f etc/ssh/ssh_host_*
: > etc/machine-id
rm -f var/lib/dbus/machine-id
passwd -R "$STAGE" -l root >/dev/null
echo 'admin:openmediavault' | chpasswd -R "$STAGE"
rm -f var/lib/samba/private/passdb.tdb var/lib/samba/private/secrets.tdb
find var/log -type f -delete
mkdir -p root && chmod 700 root
cp /etc/skel/.bashrc /etc/skel/.profile root/ 2>/dev/null || true

for f in seagate-fan.json seagate-led.json seagate-buttons.json; do cp "$DEF/$f" "etc/$f"; done
rm -f etc/ubootenv.slot0 etc/ubootenv.slot1
echo '[]' > var/lib/openmediavault/dirtymodules.json 2>/dev/null || true

echo "$HOSTNAME_NEW" > etc/hostname
sed -i "s/^127\.0\.1\.1.*/127.0.1.1\t$HOSTNAME_NEW/" etc/hosts

cat > etc/fstab <<'EOF'
# <file system> <mount point> <type> <options> <dump> <pass>
/dev/root / ext4 defaults,noatime,errors=remount-ro 0 0
# swap (stock RAID1 swap array) is added by seagate-nas2bay-firstboot
EOF

cat > etc/mdadm/mdadm.conf <<'EOF'
# Generic config for the published image. Regenerated on first boot.
DEVICE partitions
HOMEHOST <ignore>
AUTO +all
MAILADDR root
EOF
rm -f etc/lvm/backup/* etc/lvm/archive/*

python3 - "$STAGE/etc/openmediavault/config.xml" "$HOSTNAME_NEW" <<'EOF'
import sys, xml.etree.ElementTree as ET
path, host = sys.argv[1], sys.argv[2]
tree = ET.parse(path); r = tree.getroot()
def clear(xpath):
    el = r.find(xpath)
    if el is not None:
        for ch in list(el): el.remove(ch)
for x in ["./system/shares", "./services/smb/shares", "./services/nfs/shares",
          "./services/rsync/server/modules", "./services/rsync/jobs",
          "./system/usermanagement/users", "./system/usermanagement/groups"]:
    clear(x)
h = r.find("./system/network/dns/hostname")
if h is not None: h.text = host
for m in r.findall("./system/fstab/mntent"):
    c = m.find("comment")
    if c is not None: c.text = "Seagate RAID1+LVM data volume"
for el in r.iter():                       # OMV rejects whitespace-only leaf nodes
    if len(el) == 0 and el.text is not None and el.text.strip() == "":
        el.text = None
tree.write(path, encoding="utf-8", xml_declaration=True)
EOF

mkdir -p etc/seagate-nas2bay
touch etc/seagate-nas2bay/firstboot

# Samba config is generated by OMV; drop the share sections of the source system
if [ -f etc/samba/smb.conf ]; then
    awk 'BEGIN{keep=1} /^\[/{keep=($0 ~ /^\[global\]/)} keep{print}' etc/samba/smb.conf > etc/samba/smb.conf.new \
        && mv etc/samba/smb.conf.new etc/samba/smb.conf
fi

# ----------------------------------------------------------------------------- boot image
say "Rebuilding generic initramfs and uImage for $KVER"
for d in proc sys dev; do mount --bind "/$d" "$STAGE/$d"; done
trap 'for d in dev sys proc; do umount "$STAGE/$d" 2>/dev/null || true; done' EXIT
rm -f "boot/initrd.img-$KVER"
chroot "$STAGE" env TMPDIR=/var/tmp update-initramfs -c -k "$KVER"
chroot "$STAGE" /usr/sbin/seagate-mkuimage --no-install "$KVER"
for d in dev sys proc; do umount "$STAGE/$d"; done
trap - EXIT

# ----------------------------------------------------------------------------- pack
cd "$WORK"
USED_MB=$(du -sm --one-file-system "$STAGE" | awk '{print $1}')
SIZE_MB=$(( (USED_MB * 13 / 10 + 512 + 255) / 256 * 256 ))
say "Creating ext4 image (${SIZE_MB} MB, ${USED_MB} MB used)"
rm -f "$WORK/rootfs.img"
mke2fs -q -t ext4 -L DEBIAN_OMV -m 1 -d "$STAGE" "$WORK/rootfs.img" "${SIZE_MB}M"
e2fsck -fn "$WORK/rootfs.img"

say "Compressing"
gzip -6 -c "$WORK/rootfs.img" > "$OUT/seagate-nas2bay-omv7-rootfs-$VER.img.gz"
tar -czf "$OUT/seagate-nas2bay-omv7-boot-$VER.tar.gz" -C "$STAGE/boot" uImage armada-370-n090201.dtb
[ -n "$INSTALLER" ] && cp "$INSTALLER" "$OUT/install-from-stock.sh"
rm -f "$WORK/rootfs.img"
( cd "$OUT" && sha256sum seagate-nas2bay-omv7-*-"$VER".* > SHA256SUMS )
ls -l "$OUT"
say "Done. Upload the files in $OUT to the GitHub release v$VER"
